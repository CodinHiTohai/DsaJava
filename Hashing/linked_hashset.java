import java.util.*;
public class linked_hashset {
    public static void main(String[] args) {
        LinkedHashSet<String>cities=new LinkedHashSet<>();
        cities.add("delhi");
        cities.add("mumbai");
        cities.add("chennai");
        cities.add("punjab");
        cities.add("kolkata");
        cities.add("bengaluru");
        System.out.println(cities);
    }
}
